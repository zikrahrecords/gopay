create table if not exists users(
  id integer generated by default as identity (start with 100245) primary key,
  name text not null, phone text unique not null, password_hash text not null,
  role text not null default 'user' check (role in ('user','admin')),
  status text not null default 'active' check (status in ('active','blocked')),
  avatar text, referral_code text unique not null, referred_by integer references users(id),
  available_balance numeric(14,2) not null default 0 check (available_balance>=0),
  buy_balance numeric(14,2) not null default 0 check (buy_balance>=0),
  created_at timestamptz not null default now());
create table if not exists products(
  id serial primary key, short_name text not null, image_url text,
  amount numeric(14,2) not null check (amount>0), reward_rate numeric(5,2) not null check (reward_rate>=0),
  active boolean not null default true, created_at timestamptz not null default now());
create table if not exists orders(
  id serial primary key, public_id text unique not null, user_id integer not null references users(id),
  product_id integer not null references products(id), amount numeric(14,2) not null, reward numeric(14,2) not null,
  status text not null default 'processing', created_at timestamptz not null default now());
create table if not exists wallets(
  id serial primary key, user_id integer not null references users(id), provider text not null check (provider in ('bKash','Nagad','Rocket')),
  number text not null, online boolean not null default false, unique(user_id,number));
create table if not exists withdrawals(
  id serial primary key, public_id text unique not null, user_id integer not null references users(id),
  wallet_id integer not null references wallets(id), kind text not null check (kind in ('buy','available')),
  amount numeric(14,2) not null check (amount>0), completed numeric(14,2) not null default 0,
  status text not null default 'processing' check (status in ('processing','partial','paid','rejected')),
  created_at timestamptz not null default now(), check (completed<=amount));
create table if not exists withdrawal_payments(
  id serial primary key, withdrawal_id integer not null references withdrawals(id), amount numeric(14,2) not null, created_at timestamptz not null default now());
create table if not exists ledger(
  id serial primary key, user_id integer not null references users(id), type text not null, amount numeric(14,2) not null, note text not null, created_at timestamptz not null default now());
create table if not exists password_resets(
  id serial primary key, user_id integer not null references users(id), token_hash text not null, expires_at timestamptz not null, used boolean not null default false);
create table if not exists settings(key text primary key, value text not null default '');
